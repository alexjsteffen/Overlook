#!/usr/bin/env bash
# Package the current native Linux build. Invoked by the repository-root Makefile.
set -euo pipefail

format="${1:-}"
: "${ROOT_DIR:?Set ROOT_DIR}"
: "${BINARY:?Set BINARY}"
: "${BUILD_DIR:?Set BUILD_DIR}"
: "${DIST_DIR:?Set DIST_DIR}"
: "${VERSION:?Set VERSION}"
: "${PACKAGE_RELEASE:?Set PACKAGE_RELEASE}"

name="overlook"
app_id="io.github.overlook.Linux"
description="Remote console (GTK4/libadwaita) for GL.iNet GLKVM / Comet and PiKVM devices"
url="https://github.com/alexjsteffen/Overlook"
desktop="$ROOT_DIR/Linux/packaging/$app_id.desktop"
icon_dir="$ROOT_DIR/Overlook/Assets.xcassets/AppIcon.appiconset"
work="$BUILD_DIR/packages/$format"
stage="$work/root"

fail() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

require_command() {
    command -v "$1" >/dev/null 2>&1 || fail "$1 is required to build a $format package."
}

case "$format" in
    pacman|deb|rpm|appimage) ;;
    *) fail "Unknown package format '$format'. Choose pacman, deb, rpm, or appimage." ;;
esac
[[ "$(uname -s)" == "Linux" ]] || fail "Linux packages must be built on Linux."
[[ -x "$BINARY" ]] || fail "Linux binary not found at $BINARY; run 'make linux' first."
[[ "$VERSION" =~ ^[0-9A-Za-z][0-9A-Za-z.+~]*$ ]] || fail "VERSION contains unsupported characters: $VERSION"
[[ "$PACKAGE_RELEASE" =~ ^[0-9A-Za-z.]+$ ]] || fail "PACKAGE_RELEASE contains unsupported characters: $PACKAGE_RELEASE"

case "$(uname -m)" in
    x86_64|amd64)
        host_arch="x86_64"
        deb_arch="amd64"
        ;;
    aarch64|arm64)
        host_arch="aarch64"
        deb_arch="arm64"
        ;;
    *) fail "Unsupported native architecture: $(uname -m). Cross-packaging is not supported." ;;
esac

if command -v desktop-file-validate >/dev/null 2>&1; then
    desktop-file-validate "$desktop"
fi

rm -rf "$work"
mkdir -p "$stage/usr/bin" "$stage/usr/share/applications" "$DIST_DIR"
install -Dm755 "$BINARY" "$stage/usr/bin/overlook"
install -Dm644 "$desktop" "$stage/usr/share/applications/$app_id.desktop"

for icon_spec in \
    "16:icon_16x16@1x.png" \
    "32:icon_32x32@1x.png" \
    "64:icon_32x32@2x.png" \
    "128:icon_128x128@1x.png" \
    "256:icon_256x256@1x.png" \
    "512:icon_512x512@1x.png"; do
    size="${icon_spec%%:*}"
    source_name="${icon_spec#*:}"
    install -Dm644 "$icon_dir/$source_name" \
        "$stage/usr/share/icons/hicolor/${size}x${size}/apps/$app_id.png"
done

if [[ "$format" == "deb" ]]; then
    install -Dm644 "$ROOT_DIR/LICENSE.MD" "$stage/usr/share/doc/overlook/copyright"
else
    install -Dm644 "$ROOT_DIR/LICENSE.MD" "$stage/usr/share/licenses/overlook/LICENSE.MD"
fi

build_pacman() {
    require_command makepkg
    [[ "$(id -u)" -ne 0 ]] || fail "makepkg cannot run as root; use an unprivileged build user."

    cat > "$work/PKGBUILD" <<EOF
# Generated by make pacman from the current checkout.
pkgname=$name
pkgver=$VERSION
pkgrel=$PACKAGE_RELEASE
pkgdesc='$description'
arch=('$host_arch')
url='$url'
license=('GPL-3.0-only')
depends=('gtk4' 'libadwaita' 'libsecret' 'webkitgtk-6.0' 'libsoup3'
         'gstreamer' 'gst-plugins-base' 'gst-plugins-good' 'gst-plugins-bad'
         'gst-libav' 'libnice' 'glib-networking')
options=('!debug')

package() {
  cp -a "\$startdir/root/." "\$pkgdir/"
}
EOF

    local output="$DIST_DIR/overlook-$VERSION-$PACKAGE_RELEASE-$host_arch.pkg.tar.zst"
    (
        cd "$work"
        PKGDEST="$DIST_DIR" PKGEXT='.pkg.tar.zst' makepkg --force --nodeps --nocheck
    )
    [[ -f "$output" ]] || fail "makepkg did not create the expected package: $output"
    printf 'Created %s\n' "$output"
}

build_deb() {
    require_command dpkg-deb
    require_command dpkg-shlibdeps

    local shlibs dependencies installed_size output
    shlibs="$(dpkg-shlibdeps -O "$stage/usr/bin/overlook")"
    dependencies="${shlibs#shlibs:Depends=}"
    [[ "$dependencies" != "$shlibs" ]] || fail "dpkg-shlibdeps returned unexpected metadata: $shlibs"
    dependencies+=", gstreamer1.0-plugins-base, gstreamer1.0-plugins-good, gstreamer1.0-plugins-bad, gstreamer1.0-nice, gstreamer1.0-libav, glib-networking, ca-certificates"

    mkdir -p "$stage/DEBIAN"
    installed_size="$(du -sk "$stage" | cut -f1)"
    cat > "$stage/DEBIAN/control" <<EOF
Package: overlook
Version: $VERSION-$PACKAGE_RELEASE
Section: net
Priority: optional
Architecture: $deb_arch
Installed-Size: $installed_size
Maintainer: Overlook contributors
Homepage: $url
Depends: $dependencies
Description: $description
 Overlook is a native GNOME remote console for GL.iNet GLKVM / Comet and
 PiKVM devices, with WebRTC video and remote keyboard and mouse input.
EOF

    output="$DIST_DIR/overlook_${VERSION}-${PACKAGE_RELEASE}_${deb_arch}.deb"
    dpkg-deb --root-owner-group --build "$stage" "$output"
    printf 'Created %s\n' "$output"
}

build_rpm() {
    require_command rpmbuild

    mkdir -p "$work/rpmbuild"/{BUILD,RPMS,SOURCES,SPECS,SRPMS}
    cat > "$work/overlook.spec" <<EOF
Name:           overlook
Version:        $VERSION
Release:        $PACKAGE_RELEASE
Summary:        Remote console for PiKVM and GL.iNet Comet
License:        GPL-3.0-only
URL:            $url
BuildArch:      $host_arch
Requires:       gtk4 >= 4.12
Requires:       libadwaita >= 1.5
Requires:       libsecret
Requires:       webkitgtk6.0
Requires:       libsoup3
Requires:       gstreamer1
Requires:       gstreamer1-plugins-base
Requires:       gstreamer1-plugins-good
Requires:       gstreamer1-plugins-bad-free
Requires:       libnice-gstreamer1
Requires:       glib-networking
Recommends:     gstreamer1-libav
Recommends:     gstreamer1-plugin-openh264

%global debug_package %{nil}

%description
Overlook is a native GNOME remote console for GL.iNet GLKVM / Comet and
PiKVM devices, with WebRTC video and remote keyboard and mouse input.

%install
mkdir -p "%{buildroot}"
cp -a "%{overlook_stage}/." "%{buildroot}/"

%files
/usr/bin/overlook
/usr/share/applications/$app_id.desktop
/usr/share/icons/hicolor/*/apps/$app_id.png
%license /usr/share/licenses/overlook/LICENSE.MD
EOF

    rpmbuild -bb "$work/overlook.spec" \
        --define "_topdir $work/rpmbuild" \
        --define "_rpmdir $work/rpms" \
        --define "overlook_stage $stage"

    local built="$work/rpms/$host_arch/overlook-$VERSION-$PACKAGE_RELEASE.$host_arch.rpm"
    local output="$DIST_DIR/overlook-$VERSION-$PACKAGE_RELEASE.$host_arch.rpm"
    [[ -f "$built" ]] || fail "rpmbuild did not create the expected package: $built"
    cp "$built" "$output"
    printf 'Created %s\n' "$output"
}

build_appimage() {
    local linuxdeploy="${LINUXDEPLOY:-linuxdeploy}"
    local appimagetool="${APPIMAGETOOL:-appimagetool}"
    require_command "$linuxdeploy"
    require_command "$appimagetool"
    require_command patchelf
    require_command pkg-config
    require_command file
    require_command find
    if [[ -e /etc/debian_version ]]; then
        require_command dpkg-architecture
    fi
    pkg-config --exists librsvg-2.0 || fail "librsvg development metadata is required by linuxdeploy-plugin-gtk (Ubuntu/Debian: librsvg2-dev)."
    pkg-config --exists gobject-introspection-1.0 || fail "GObject Introspection development metadata is required by linuxdeploy-plugin-gtk (Ubuntu/Debian: libgirepository1.0-dev)."
    export APPIMAGE_EXTRACT_AND_RUN=1

    local plugins
    if ! plugins="$("$linuxdeploy" --list-plugins 2>&1)"; then
        printf '%s\n' "$plugins" >&2
        fail "Could not run linuxdeploy. Check LINUXDEPLOY and AppImage/FUSE support."
    fi
    grep -q 'gtk' <<<"$plugins" || fail "linuxdeploy-plugin-gtk is required; put it next to linuxdeploy or in PATH."
    grep -q 'gstreamer' <<<"$plugins" || fail "linuxdeploy-plugin-gstreamer is required; put it next to linuxdeploy or in PATH."

    # Production WebKitGTK builds use a compiled-in absolute helper directory
    # and ignore WEBKIT_EXEC_PATH. Do not ship a console that could spawn an
    # incompatible host helper: the app disables only its Web Console button
    # when this variable is set. Native WebRTC remains available.
    mkdir -p "$stage/apprun-hooks"
    cat > "$stage/apprun-hooks/overlook-appimage.sh" <<'EOF'
export OVERLOOK_DISABLE_WEB_CONSOLE=1
EOF

    export DEPLOY_GTK_VERSION=4
    export GSTREAMER_INCLUDE_BAD_PLUGINS=1
    export GSTREAMER_PLUGINS_DIR="$(pkg-config --variable=pluginsdir gstreamer-1.0)"
    export GSTREAMER_HELPERS_DIR="$(pkg-config --variable=pluginscannerdir gstreamer-1.0)"
    [[ -d "$GSTREAMER_PLUGINS_DIR" ]] || fail "GStreamer plugin directory not found: $GSTREAMER_PLUGINS_DIR"
    [[ -d "$GSTREAMER_HELPERS_DIR" ]] || fail "GStreamer helper directory not found: $GSTREAMER_HELPERS_DIR"

    "$linuxdeploy" --appdir "$stage" --plugin gtk --plugin gstreamer
    [[ -e "$stage/AppRun" ]] || fail "linuxdeploy did not create AppRun."

    # AppImage desktop integration expects these at the AppDir root as well as
    # in their normal hicolor/applications locations.
    [[ -e "$stage/$app_id.desktop" ]] || cp "$desktop" "$stage/$app_id.desktop"
    [[ -e "$stage/$app_id.png" ]] || cp "$icon_dir/icon_512x512@1x.png" "$stage/$app_id.png"
    [[ -e "$stage/.DirIcon" ]] || cp "$icon_dir/icon_512x512@1x.png" "$stage/.DirIcon"

    local output="$DIST_DIR/Overlook-$VERSION-$host_arch.AppImage"
    ARCH="$host_arch" "$appimagetool" "$stage" "$output"
    chmod +x "$output"
    printf 'Created %s\n' "$output"
}

case "$format" in
    pacman) build_pacman ;;
    deb) build_deb ;;
    rpm) build_rpm ;;
    appimage) build_appimage ;;
esac
